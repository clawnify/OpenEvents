import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

// Each run kind dispatches its own skill as the agent's instruction. The agent
// accepts at most 4,000 characters, and the task data line takes ~200 of them.
const LIMIT = 3700;
const skills = { shortlist: "event-shortlist", send: "event-send", inbox: "event-inbox" };

const entries = Object.entries(skills).map(([kind, folder]) => {
  const content = readFileSync(new URL(`../skills/${folder}/SKILL.md`, import.meta.url), "utf8");
  const version = content.match(/^version: (\d+)$/m)?.[1];
  if (!version) throw new Error(`${folder} must declare an integer version`);
  if (content.length > LIMIT) throw new Error(`${folder} is ${content.length} characters; keep it under ${LIMIT}`);
  const hash = createHash("sha256").update(content).digest("hex");
  return `  ${kind}: ${JSON.stringify({ name: folder, version, hash, content })},`;
});

writeFileSync(
  new URL("../src/server/skills.gen.ts", import.meta.url),
  `// Generated by scripts/build-skills.mjs. Edit skills/*/SKILL.md.\nexport const SKILLS = {\n${entries.join("\n")}\n} as const;\n`,
);
